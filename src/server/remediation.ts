export type RemediationFile = {
  path: string;
  content: string;
};

const CUSTOMER_OWNED_PATHS = new Set([
  ".gitignore",
  ".npmignore",
  ".nospoilers.yml",
  SETUP_WORKFLOW_PATH,
  SETUP_ACTION_PATH,
]);

