export function remediationBundle(): RemediationFile[] {
  return [
    { path: ".gitignore", content: remediationGitignore() },
    { path: ".npmignore", content: remediationNpmignore() },
    { path: ".nospoilers.yml", content: remediationPolicyYaml() },
    { path: ".nospoilers/bundler-hints.md", content: remediationBundlerHints() },
    { path: ".nospoilers/package-files.snippet.json", content: remediationPackageFilesSnippet() },
    { path: SETUP_WORKFLOW_PATH, content: setupWorkflowYaml() },
    { path: SETUP_ACTION_PATH, content: setupActionYaml() },
  ];
}

export function isCustomerOwnedRemediationPath(filePath: string): boolean {
  return CUSTOMER_OWNED_PATHS.has(filePath);
}

export function remediationWrites(existingPaths: string[]): RemediationFile[] {
  const existing = new Set(existingPaths.map((row) => row.replace(/^\.\//, "")));
  const writes: RemediationFile[] = [];
  for (const file of remediationBundle()) {
    if (existing.has(file.path) && isCustomerOwnedRemediationPath(file.path)) {
      if (file.path === ".gitignore") {
        writes.push({ path: ".nospoilers/gitignore.append", content: file.content });
      }
      if (file.path === ".npmignore") {
        writes.push({ path: ".nospoilers/npmignore.append", content: file.content });
      }
      continue;
    }
    writes.push(file);
  }
  return writes;
}

